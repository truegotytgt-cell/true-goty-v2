type SocialBarProps = {
  corPrincipal: string;
  corHoverBg: string;
  isGenerating: boolean;
  onShare: (rede: RedeSocial) => void;
};

const BOTOES: { rede: RedeSocial; label: string; Icon: React.FC }[] = [
  { rede: 'whatsapp', label: 'Compartilhar no WhatsApp', Icon: IconWhatsApp },
  { rede: 'x', label: 'Compartilhar no X', Icon: IconX },
  { rede: 'reddit', label: 'Compartilhar no Reddit', Icon: IconReddit },
  { rede: 'instagram', label: 'Baixar Story para o Instagram', Icon: IconInstagram },
  { rede: 'discord', label: 'Compartilhar no Discord', Icon: IconDiscord },
];

export function SocialShareBar({
  corPrincipal,
  corHoverBg,
  isGenerating,
  onShare,
}: SocialBarProps) {
  const estiloBotao: React.CSSProperties = {
    display: 'flex',
    alignItems: 'center',
    justifyContent: 'center',
    width: '48px',
    height: '48px',
    backgroundColor: 'rgba(255, 255, 255, 0.05)',
    border: '1px solid rgba(255, 255, 255, 0.14)',
    color: '#A1A1AA',
    borderRadius: '0px',
    transition: 'all 0.2s',
    cursor: isGenerating ? 'wait' : 'pointer',
  };

  return (
    <div style={{ display: 'flex', justifyContent: 'center', flexWrap: 'wrap', gap: '0.8rem', marginBottom: '2rem' }}>
      {BOTOES.map(({ rede, label, Icon }) => (
        <button
          key={rede}
          type="button"
          title={label}
          aria-label={label}
          disabled={isGenerating}
          onClick={() => onShare(rede)}
          style={estiloBotao}
          onMouseOver={(e) => {
            e.currentTarget.style.color = '#FFF';
            e.currentTarget.style.borderColor = corPrincipal;
            e.currentTarget.style.backgroundColor = corHoverBg;
          }}
          onMouseOut={(e) => {
            e.currentTarget.style.color = '#A1A1AA';
            e.currentTarget.style.borderColor = 'rgba(255, 255, 255, 0.14)';
            e.currentTarget.style.backgroundColor = 'rgba(255, 255, 255, 0.05)';
          }}
        >
          <Icon />
        </button>
      ))}
    </div>
  );
}